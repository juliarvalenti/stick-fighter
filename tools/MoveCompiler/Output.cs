using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.Json;
using StickFighter.Sim.Characters;

namespace StickFighter.MoveCompiler;

// Writes compiled moves in the format CharacterLoader reads: one pose key per frame where the pose
// changes (keys hold), integers only, one key per line so diffs stay readable.
public static class Output
{
    public static string Write(IEnumerable<CompiledMove> moves)
    {
        var text = new StringBuilder();
        text.Append("{\n");
        text.Append("  \"comment\": \"GENERATED by tools/MoveCompiler from data/moves/. Don't edit: change the scripts and recompile.\",\n");
        text.Append("  \"moves\": [\n");
        var firstMove = true;
        foreach (var move in moves)
        {
            if (!firstMove)
                text.Append(",\n");
            firstMove = false;
            WriteMove(text, move);
        }
        text.Append("\n  ]\n}\n");
        return text.ToString();
    }

    // The integer keys a move compiles to, in frame order, with repeated poses dropped.
    public static List<(int Frame, int[] Values)> Keys(CompiledMove move)
    {
        var keys = new List<(int, int[])>();
        int[]? previous = null;
        for (var frame = 0; frame < move.Frames.Count; frame++)
        {
            var values = Round(move.Frames[frame]);
            if (previous is null || !Same(previous, values))
                keys.Add((frame, values));
            previous = values;
        }
        return keys;
    }

    private static void WriteMove(StringBuilder text, CompiledMove move)
    {
        var s = move.Script;
        text.Append("    {\n");
        Field(text, "name", Str(s.GetProperty("name").GetString()!));
        Field(text, "input", Str(move.Input));
        foreach (var key in new[] { "startup", "active", "recovery", "damage", "stun" })
            Field(text, key, s.GetProperty(key).GetInt32().ToString(CultureInfo.InvariantCulture));
        Field(text, "strength", Str(s.GetProperty("strength").GetString()!));
        Field(text, "guard", Str(s.GetProperty("guard").GetString()!));
        if (s.TryGetProperty("kind", out var kind))
            Field(text, "kind", Str(kind.GetString()!));
        foreach (var key in new[] { "chip" })
        {
            if (s.TryGetProperty(key, out var value))
                Field(text, key, value.GetInt32().ToString(CultureInfo.InvariantCulture));
        }
        if (s.TryGetProperty("chipKo", out var chipKo))
            Field(text, "chipKo", chipKo.GetBoolean() ? "true" : "false");
        foreach (var key in new[] { "pushbackHit", "pushbackBlock", "hitstun", "blockstun" })
        {
            if (s.TryGetProperty(key, out var value))
                Field(text, key, value.GetInt32().ToString(CultureInfo.InvariantCulture));
        }
        Field(text, "hitbox", $"{{ \"limb\": {Str(Camel(move.HitboxLimb))}, \"radius\": {move.HitboxRadius}, \"activeBonus\": 0 }}");
        if (move.Hurt.Count > 0)
        {
            var parts = new List<string>();
            foreach (var (limb, mode, from, to) in move.Hurt)
                parts.Add($"{{ \"limb\": {Str(Camel(limb))}, \"mode\": {Str(Camel(mode))}, \"from\": {from}, \"to\": {to} }}");
            Field(text, "hurt", "[" + string.Join(", ", parts) + "]");
        }
        if (move.Spawn is { } spawn)
            Field(text, "spawn", $"{{ \"frame\": {spawn.Frame}, \"from\": {Str(Camel(spawn.From))} }}");

        text.Append("      \"keys\": [\n");
        var keys = Keys(move);
        for (var i = 0; i < keys.Count; i++)
        {
            var (frame, v) = keys[i];
            text.Append("        ").Append(Key(frame, v)).Append(i < keys.Count - 1 ? ",\n" : "\n");
        }
        text.Append("      ]\n    }");
    }

    // One pose key on one line: `{ "frame": 0, "hip": [x, y], "angles": { ... } }`.
    public static string Key(int frame, int[] v)
    {
        var text = new StringBuilder();
        text.Append("{ \"frame\": ").Append(frame)
            .Append(", \"hip\": [").Append(v[0]).Append(", ").Append(v[1]).Append("], \"angles\": { ");
        for (var j = 0; j < 10; j++)
        {
            if (j > 0)
                text.Append(", ");
            text.Append('"').Append(FloatPose.Names[j]).Append("\": ").Append(v[2 + j]);
        }
        return text.Append(" } }").ToString();
    }

    public static int[] Round(FloatPose p)
    {
        var v = new int[12];
        v[0] = (int)Math.Round(p.HipX, MidpointRounding.AwayFromZero);
        v[1] = (int)Math.Round(p.HipY, MidpointRounding.AwayFromZero);
        for (var i = 0; i < 10; i++)
            v[2 + i] = (int)Math.Round(Rig.Wrap(p.A[i]), MidpointRounding.AwayFromZero);
        return v;
    }

    public static bool Same(int[] a, int[] b)
    {
        for (var i = 0; i < a.Length; i++)
        {
            if (a[i] != b[i])
                return false;
        }
        return true;
    }

    private static void Field(StringBuilder text, string key, string value) =>
        text.Append("      \"").Append(key).Append("\": ").Append(value).Append(",\n");

    private static string Str(string value) => JsonSerializer.Serialize(value);

    private static string Camel(string name) => char.ToLowerInvariant(name[0]) + name[1..];
}
